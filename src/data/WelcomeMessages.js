/**
 * Get welcome messages for the current language
 */
export const getWelcomeMessages = () => {
  const currentLanguage = i18n.language || 'en';
  return WELCOME_MESSAGES[currentLanguage] || WELCOME_MESSAGES.en;
};

/**
 * Get a random welcome message
 * @param {string[]} preferredTags - Array of preferred tags to filter by
 * @returns {Object} Random welcome message object
 */
export const getRandomWelcomeMessage = (preferredTags = []) => {
  const messages = getWelcomeMessages();
  
  // If no preferred tags, return any message
  if (preferredTags.length === 0) {
    const randomIndex = Math.floor(Math.random() * messages.length);
    return messages[randomIndex];
  }
  
  // Filter messages by preferred tags
  const filteredMessages = messages.filter(message => 
    preferredTags.some(tag => message.tags.includes(tag))
  );
  
  // If no matches found, return any message
  const messagesToUse = filteredMessages.length > 0 ? filteredMessages : messages;
  const randomIndex = Math.floor(Math.random() * messagesToUse.length);
  return messagesToUse[randomIndex];
};

/**
 * Get time-based welcome message
 * @returns {Object} Welcome message appropriate for current time
 */
export const getTimeBasedWelcomeMessage = () => {
  const hour = new Date().getHours();
  
  if (hour >= 5 && hour < 12) {
    return getRandomWelcomeMessage(['morning', 'energetic', 'professional']);
  } else if (hour >= 12 && hour < 17) {
    return getRandomWelcomeMessage(['afternoon', 'helpful', 'efficient']);
  } else if (hour >= 17 && hour < 21) {
    return getRandomWelcomeMessage(['friendly', 'casual', 'helpful']);
  } else {
    return getRandomWelcomeMessage(['basic', 'professional', 'concise']);
  }
};

/**
 * Get returning user welcome message
 * @returns {Object} Welcome message for returning users
 */
export const getReturningUserMessage = () => {
  return getRandomWelcomeMessage(['returning-user', 'friendly', 'continuity']);
};

/**
 * Get welcome message by style
 * @param {string} style - Style preference: 'formal', 'casual', 'enthusiastic', 'helpful'
 * @returns {Object} Welcome message matching the specified style
 */
export const getWelcomeMessageByStyle = (style = 'friendly') => {
  const styleMap = {
    formal: ['professional', 'formal', 'technical'],
    casual: ['casual', 'informal', 'friendly'],
    enthusiastic: ['enthusiastic', 'engaging', 'interactive'],
    helpful: ['helpful', 'educational', 'supportive'],
    friendly: ['friendly', 'basic', 'general']
  };
  
  const tags = styleMap[style] || styleMap.friendly;
  return getRandomWelcomeMessage(tags);
};

